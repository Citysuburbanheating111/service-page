#!/usr/bin/env node
// Build src/brand-pages/qc-rules.json: the rules the Studio checks every brand page against before it can be published.
// They come from the citysuburban-brand-service-pages skill, so the Studio and the writing skill check the same things:
//   - required fields: every field the skill's approved example fills (on every list item), minus its optional paths
//   - photo slots, placeholder and [CONFIRM] text, designer and photo notes, forbidden claims, other clients' names
// Run again when the skill's example or spec changes:
//   node scripts/build-brand-page-qc-rules.mjs <skill folder>
import fs from 'node:fs'
import path from 'node:path'

const skill = process.argv[2] || process.env.BRAND_SKILL_DIR
if (!skill) {
  console.error('Usage: node scripts/build-brand-page-qc-rules.mjs <citysuburban-brand-service-pages skill folder>')
  process.exit(1)
}
const spec = JSON.parse(fs.readFileSync(path.join(skill, 'spec/brand-spec.json'), 'utf8'))
const example = JSON.parse(fs.readFileSync(path.join(skill, spec.example || 'assets/example-american-standard-furnace.json'), 'utf8'))

const present = (v) => !(v === null || v === undefined || v === '' || (Array.isArray(v) && !v.length) ||
  (typeof v === 'object' && !Array.isArray(v) && !Object.keys(v).length) || (typeof v === 'string' && !v.trim()))
const norm = (p) => p.replace(/\[\d+\]/g, '[]')

function* leaves(o, p = '') {
  if (Array.isArray(o)) {
    if (!o.length) yield [p, []]
    for (let i = 0; i < o.length; i++) yield* leaves(o[i], `${p}[${i}]`)
  } else if (o && typeof o === 'object') {
    for (const [k, v] of Object.entries(o)) yield* leaves(v, p ? `${p}.${k}` : k)
  } else yield [p, o]
}

/** Every concrete value of a normalized path ('services.groups[].services[].title'). */
function instances(page, npath) {
  let out = [['', page]]
  for (const part of npath.split(/\.(?![^[]*\])/)) {
    const many = part.endsWith('[]')
    const key = many ? part.slice(0, -2) : part
    const next = []
    for (const [p, o] of out) {
      const v = o && typeof o === 'object' && !Array.isArray(o) ? o[key] : undefined
      const q = p ? `${p}.${key}` : key
      if (many) { if (Array.isArray(v)) v.forEach((x, i) => next.push([`${q}[${i}]`, x])) } else next.push([q, v])
    }
    out = next
  }
  return out
}

const sections = spec.sanity.pushed_sections
const fixed = spec.fixed_blocks || []
const optional = new Set(spec.optional_paths || [])
const required = new Set()
for (const [p] of leaves(example)) {
  const n = norm(p)
  const top = n.split(/[.[]/)[0]
  if (!sections.includes(top) || fixed.includes(top) || optional.has(n)) continue
  if (instances(example, n).every(([, x]) => present(x))) required.add(n)
}

const h = spec.text_hygiene
const rules = {
  note: 'Generated by scripts/build-brand-page-qc-rules.mjs from the citysuburban-brand-service-pages skill. Do not edit by hand.',
  skillVersion: spec.version,
  sections,
  required: [...required].sort(),
  imagePaths: spec.image_paths,
  imageLicenses: spec.image_licenses,
  seoTitleMax: 60,
  metaDescriptionMax: 155,
  placeholders: h.placeholders,
  designerNotes: spec.voice_banned,
  // other clients and the agency: never on a City & Suburban page
  otherNames: spec.white_label_block,
  forbidden: spec.forbidden_claims.map((f) => ({pattern: f.pattern, reason: f.reason})),
  bannedPricePhrases: spec.banned_price_phrases,
  // keys that hold links, photos or internal records, not visible copy
  skipKeys: ['url', 'image', 'logo', 'drawing', 'slug', 'imageSources', 'primaryKeyword', 'secondaryKeywords', 'city',
    'brand', 'equipment', 'service', 'priceDate', 'sources', 'mapEmbedUrl', 'sourceRef'],
}
fs.writeFileSync('src/brand-pages/qc-rules.json', JSON.stringify(rules, null, 2) + '\n')
console.log(`src/brand-pages/qc-rules.json: ${rules.required.length} required fields, ${rules.imagePaths.length} photo slot paths (skill ${spec.version})`)
